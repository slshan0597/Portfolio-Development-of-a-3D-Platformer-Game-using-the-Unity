using UnityEngine;

// //////////////////////////////////////////////////////////////////////////////
// 1. 인터페이스
// //////////////////////////////////////////////////////////////////////////////
public interface ICameraTargetController
{
    // 프로퍼티
    // Component
    Transform transform { get; }
    Transform endPoint  { get; }
}

// //////////////////////////////////////////////////////////////////////////////
// 2. 클래스
// //////////////////////////////////////////////////////////////////////////////
public class CameraTargetController : MonoBehaviour, ICameraTargetController
{
    // ==============================================================================
    // 1) 필드
    // ==============================================================================
    // Component & Reference
    public Transform endPoint { get; protected set; }

    // ==============================================================================
    // 2) 메서드
    // ==============================================================================
    // ------------------------------------------------------------------------------
    // 2-1) 메서드 -> 이벤트 함수
    // ------------------------------------------------------------------------------
    protected virtual void Awake() { SetField(); }

    // ------------------------------------------------------------------------------
    // 2-2) 메서드 -> 초기화
    // ------------------------------------------------------------------------------
    protected virtual void SetField() { endPoint = transform.GetChild(0); }
}
