using UnityEngine;

using Type = PowerUpItemController.Type;

// //////////////////////////////////////////////////////////////////////////////
// 1. 인터페이스(IItemBase 인터페이스 상속)
// //////////////////////////////////////////////////////////////////////////////
public interface IPowerUpItemController : IItemBase
{
    // 프로퍼티
    // Setting
    Type type { get; }
}

// //////////////////////////////////////////////////////////////////////////////
// 2. 클래스(ItemBase 클래스 상속)
// //////////////////////////////////////////////////////////////////////////////
public class PowerUpItemController : ItemBase, IPowerUpItemController
{
    public enum Type { None, FireFlower, SuperStar }

    // ==============================================================================
    // 1) 필드
    // ==============================================================================
    // Setting
    [SerializeField] protected Type _type;

    public Type type { get { return _type; } }

    // ==============================================================================
    // 2) 메서드
    // ==============================================================================
    // ------------------------------------------------------------------------------
    // 2-1) 메서드 -> 이벤트 함수
    // ------------------------------------------------------------------------------
    protected virtual void Reset() { ResetField(); }

    // ------------------------------------------------------------------------------
    // 2-2) 메서드 -> 초기화
    // ------------------------------------------------------------------------------
    protected virtual void ResetField() { _lifeSpan = 10f; }

    // ------------------------------------------------------------------------------
    // 2-3) 메서드 -> 액션
    // ------------------------------------------------------------------------------
    // ******************************************************************************
    // 2-3-1) 메서드 -> 액션 -> 획득(Get)
    //    - 획득 시 플레이어 파워업 기능 호출
    // ******************************************************************************
    public override Coroutine Get(IPlayerController player)
    {
        player.PowerUp(type);

        return base.Get(player);
    }
}
